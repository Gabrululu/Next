// Copies compiled ABIs from Foundry output into scripts/lib/abi.ts (and web, once it exists).
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
const read = (n) => JSON.parse(readFileSync(new URL(`../contracts/out/${n}.sol/${n}.json`, import.meta.url))).abi;
const src = `// AUTO-GENERATED by scripts/gen-abi.mjs from contracts/out — do not edit.
export const nextAbi = ${JSON.stringify(read("Next"), null, 2)} as const;

export const disperseAbi = ${JSON.stringify(read("Disperse"), null, 2)} as const;

export const nextPassAbi = ${JSON.stringify(read("NextPass"), null, 2)} as const;
`;
writeFileSync(new URL("./lib/abi.ts", import.meta.url), src);
const web = new URL("../web/src/lib/shared/", import.meta.url);
if (existsSync(new URL("../web/src", import.meta.url))) {
  mkdirSync(web, { recursive: true });
  writeFileSync(new URL("abi.ts", web), src);
  writeFileSync(new URL("select.ts", web), "// AUTO-COPIED from scripts/lib/select.ts by scripts/gen-abi.mjs — edit the original.\n" + readFileSync(new URL("./lib/select.ts", import.meta.url), "utf8"));
}
const indexer = new URL("../indexer/", import.meta.url);
if (existsSync(indexer)) {
  mkdirSync(new URL("abis/", indexer), { recursive: true });
  for (const n of ["Next", "NextPass"]) writeFileSync(new URL(`abis/${n}.json`, indexer), JSON.stringify(read(n), null, 2) + "\n");
}
console.log("ABIs written");
